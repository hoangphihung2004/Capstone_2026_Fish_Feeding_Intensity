class AudioCircularBuffer:
    """Fixed-capacity real-time circular audio buffer (128k samples @ 64kHz = 512 KB RAM)."""

    def __init__(self, capacity: int = 128000):
        self.capacity = capacity
        self.buf = np.zeros(capacity, dtype=np.float32)
        self.pos = 0

    def extend(self, chunk: np.ndarray):
        n = len(chunk)
        if n >= self.capacity:
            self.buf[:] = chunk[-self.capacity:]
            self.pos = 0
        else:
            space = self.capacity - self.pos
            if n <= space:
                self.buf[self.pos:self.pos + n] = chunk
                self.pos = (self.pos + n) % self.capacity
            else:
                self.buf[self.pos:] = chunk[:space]
                rem = n - space
                self.buf[:rem] = chunk[space:]
                self.pos = rem

    def get_window(self) -> np.ndarray:
        if self.pos == 0:
            return self.buf
        return np.concatenate([self.buf[self.pos:], self.buf[:self.pos]])


class ContinuousStreamManager:
    """Same 2.0 s windowing as the main dashboard; calls model.py for inference."""

    def __init__(self):
        self.video_rel = f"continuous_simulation/{SIM_NAME}.mp4"
        self.audio_rel = f"continuous_simulation/{SIM_NAME}.wav"
        self.video_path = os.path.join(SIM_DIR, f"{SIM_NAME}.mp4")
        self.audio_path = os.path.join(SIM_DIR, f"{SIM_NAME}.wav")

        self.current_step = 0
        self.window_sec = 2.0
        self.total_duration_sec = 598.0
        self.total_steps = int(self.total_duration_sec / self.window_sec)  # 299 steps

        self.video_ring = collections.deque(maxlen=50)
        self.audio_ring = AudioCircularBuffer(capacity=128000)
        self.cap = None
        self.fps = 25.0
        self.audio_full = None
        self.audio_sr = 256000
        self.audio_hop = 0
        self.resampler = None
        self._is_initialized = False
        self._lock = threading.Lock()

    def is_available(self) -> bool:
        return os.path.exists(self.video_path) and os.path.exists(self.audio_path)

    def _ensure_loaded(self):
        with self._lock:
            if self._is_initialized:
                return
            if not self.is_available():
                raise HTTPException(status_code=404, detail=f"Continuous simulation files not found in {SIM_DIR}.")

            self.cap = cv2.VideoCapture(self.video_path)
            self.fps = self.cap.get(cv2.CAP_PROP_FPS) or 25.0

            self.audio_full, self.audio_sr = sf.read(self.audio_path, dtype="float32")
            if self.audio_full.ndim > 1:
                self.audio_full = self.audio_full.mean(axis=1)

            self.audio_hop = int(self.window_sec * self.audio_sr)
            if self.audio_sr != 64000:
                self.resampler = torchaudio.transforms.Resample(self.audio_sr, 64000)

            self._fill_window(step=0)
            self._is_initialized = True
            logger.info("Stream reader ready (%s).", self.video_path)

    def _fill_window(self, step: int):
        """Fills the 2.0-second sliding ring buffer for a given step timestamp."""
        time_sec = step * self.window_sec
        target_frame_start = int(time_sec * self.fps)

        self.cap.set(cv2.CAP_PROP_POS_FRAMES, target_frame_start)
        self.video_ring.clear()
        frames_to_read = int(self.window_sec * self.fps)
        for _ in range(frames_to_read):
            ret, frame = self.cap.read()
            if not ret:
                break
            self.video_ring.append(frame)

        start_samp = int(time_sec * self.audio_sr)
        end_samp = start_samp + self.audio_hop
        chunk_raw = self.audio_full[start_samp:end_samp]
        if len(chunk_raw) > 0:
            if self.resampler:
                chunk_64k = self.resampler(torch.from_numpy(chunk_raw).unsqueeze(0)).squeeze(0).numpy()
            else:
                chunk_64k = chunk_raw
            self.audio_ring.extend(chunk_64k[-128000:])
        self.current_step = step

    def step(self, target_step: Optional[int] = None) -> dict:
        self._ensure_loaded()
        with self._lock:
            if target_step is not None and target_step != self.current_step:
                self.current_step = target_step % self.total_steps
                self._fill_window(self.current_step)
            else:
                frames_to_read = int(self.window_sec * self.fps)
                for _ in range(frames_to_read):
                    ret, frame = self.cap.read()
                    if not ret:
                        self.cap.set(cv2.CAP_PROP_POS_FRAMES, 0)
                        ret, frame = self.cap.read()
                    if ret:
                        self.video_ring.append(frame)

                time_sec = self.current_step * self.window_sec
                start_samp = int(time_sec * self.audio_sr)
                end_samp = start_samp + self.audio_hop
                if end_samp <= len(self.audio_full):
                    chunk_raw = self.audio_full[start_samp:end_samp]
                else:
                    chunk_raw = self.audio_full[start_samp:]
                if len(chunk_raw) > 0:
                    if self.resampler:
                        chunk_64k = self.resampler(torch.from_numpy(chunk_raw).unsqueeze(0)).squeeze(0).numpy()
                    else:
                        chunk_64k = chunk_raw
                    self.audio_ring.extend(chunk_64k[:128000])

            # Latency is measured from the moment the full 2.0 s window is in the buffers.
            t_start = time.perf_counter()
            time_sec = self.current_step * self.window_sec

            # 1. Audio: waveform window + telemetry envelope (identical to main dashboard)
            t_a0 = time.perf_counter()
            waveform_slice = self.audio_ring.get_window()

            w_raw = waveform_slice[:128000]
            w_centered = w_raw - np.mean(w_raw)

            peak_amp = float(np.max(np.abs(w_centered)))
            rms_val = float(np.sqrt(np.mean(w_centered**2)))
            audio_rms_db = round(float(20 * np.log10(max(1e-5, rms_val))), 1)

            n_bins = 600
            bin_size = 128000 // n_bins
            w_bins = w_centered[: n_bins * bin_size].reshape(n_bins, bin_size)
            bin_mins = w_bins.min(axis=1)
            bin_maxs = w_bins.max(axis=1)
            bin_rms = np.sqrt(np.mean(w_bins**2, axis=1))

            headroom = max(0.12, min(0.60, peak_amp * 1.15))
            mins_norm = np.clip(bin_mins / headroom, -1.0, 1.0)
            maxs_norm = np.clip(bin_maxs / headroom, -1.0, 1.0)
            rms_norm = np.clip(bin_rms / headroom, 0.0, 1.0)

            audio_envelope = [
                [round(float(mn), 3), round(float(mx), 3), round(float(r), 3)]
                for mn, mx, r in zip(mins_norm, maxs_norm, rms_norm)
            ]

            audio_input = model.preprocess_audio(np.ascontiguousarray(waveform_slice, dtype=np.float32))
            t_audio = (time.perf_counter() - t_a0) * 1000.0

            # 2. Video: first and last frame of the window (native resolution, BGR uint8)
            t_v0 = time.perf_counter()
            if len(self.video_ring) > 0:
                f0 = self.video_ring[0]
                f1 = self.video_ring[-1]
            else:
                f0 = np.zeros((224, 224, 3), dtype=np.uint8)
                f1 = np.zeros((224, 224, 3), dtype=np.uint8)
            video_input = model.preprocess_video(f0, f1)
            t_video = (time.perf_counter() - t_v0) * 1000.0

            # 3. Model inference
            t_g0 = time.perf_counter()
            outputs = np.asarray(model.infer(audio_input, video_input), dtype=np.float32).reshape(1, -1)
            t_gpu = (time.perf_counter() - t_g0) * 1000.0
            t_total = (time.perf_counter() - t_start) * 1000.0

            # 4. Softmax & decisions (identical to main dashboard)
            if OUTPUT_IS_PROBABILITY:
                probs = outputs[0] / max(1e-12, float(np.sum(outputs[0])))
            else:
                exp_logits = np.exp(outputs - np.max(outputs, axis=1, keepdims=True))
                probs = (exp_logits / np.sum(exp_logits, axis=1, keepdims=True))[0]
            pred_class = int(np.argmax(probs))
            class_name = CLASS_NAMES[pred_class]
            confidence = float(probs[pred_class])

            if pred_class in (1, 2):
                feeder_relay = "ON"
                feeder_status = "FEEDING IN PROGRESS"
                feeder_reason = "Active surface strike detected. Sustaining automated pellet dispenser."
                feeder_color = "emerald"
            else:
                feeder_relay = "OFF"
                feeder_status = "FEED CUTOFF (PREVENT WASTE)"
                feeder_reason = "Feeding satiety threshold reached. Cutoff triggered to protect water quality."
                feeder_color = "error"

            m_cur = int(time_sec // 60)
            s_cur = int(time_sec % 60)
            m_tot = int(self.total_duration_sec // 60)
            s_tot = int(self.total_duration_sec % 60)
            time_str = f"{m_cur:02d}:{s_cur:02d} / {m_tot:02d}:{s_tot:02d}"

            executed_step = self.current_step
            self.current_step = (self.current_step + 1) % self.total_steps

            return {
                "predicted_class": pred_class,
                "class_name": class_name,
                "confidence": round(confidence * 100.0, 2),
                "probabilities": {
                    "none": round(float(probs[0]) * 100.0, 2),
                    "strong": round(float(probs[1]) * 100.0, 2),
                    "medium": round(float(probs[2]) * 100.0, 2),
                    "weak": round(float(probs[3]) * 100.0, 2),
                },
                "latency": {
                    "audio_ms": round(t_audio, 1),
                    "video_ms": round(t_video, 1),
                    "gpu_ms": round(t_gpu, 1),
                    "total_ms": round(t_total, 1),
                    "fps": round(1000.0 / max(0.1, t_gpu), 1),
                    "pipeline_fps": round(1000.0 / max(1.0, t_total), 1),
                },
                "feeder_action": {
                    "relay": feeder_relay,
                    "status": feeder_status,
                    "reason": feeder_reason,
                    "color": feeder_color,
                },
                "audio_telemetry": {
                    "waveform": audio_envelope,
                    "rms_db": audio_rms_db,
                    "peak_amp": round(peak_amp, 3),
                    "window_sec": self.window_sec,
                    "sample_rate": 64000,
                },
                "frame_base64": None,
                "stream_info": {
                    "step": executed_step,
                    "next_step": self.current_step,
                    "total_steps": self.total_steps,
                    "time_sec": round(time_sec, 1),
                    "time_str": time_str,
                    "window_sec": self.window_sec,
                    "video_url": f"/samples/{self.video_rel}",
                    "audio_url": f"/samples/{self.audio_rel}",
                    "session": "2022_6_19 · AM_100",
                },
            }

    def reset(self):
        with self._lock:
            self.current_step = 0
            if self._is_initialized:
                self._fill_window(0)
            return {"status": "reset", "step": 0, "time_sec": 0.0}


# ==============================================================================
# FASTAPI APP
# ==============================================================================
app = FastAPI(title=f"AquaFFIA - {DEPLOYMENT_NAME}", version="1.0.0")

# The dashboard page is served from port 8001 and calls this API from the browser.
app.add_middleware(
    CORSMiddleware,
    allow_origin_regex=r"^https?://[^/]+:8001$",
    allow_methods=["GET", "POST"],
    allow_headers=["*"],
)

stream_manager = ContinuousStreamManager()


@app.on_event("startup")
def startup_event():
    """Load the model and warm it up before the server accepts requests."""
    logger.info("Loading %s (%s) from %s ...", DEPLOYMENT_NAME, MODEL_MODULE, WEIGHTS_DIR)
    model.load(WEIGHTS_DIR)
    stream_manager._ensure_loaded()
    for i in range(WARMUP_STEPS):
        stream_manager.step(target_step=i)
    stream_manager.reset()
    logger.info("%s ready after %d warmup steps.", DEPLOYMENT_NAME, WARMUP_STEPS)


@app.get("/api/status")
async def get_system_status():
    return {
        "status": "online",
        "deployment_id": DEPLOYMENT_ID,
        "deployment_name": DEPLOYMENT_NAME,
        "model_name": MODEL_INFO.get("name", "unknown"),
        "runtime": MODEL_INFO.get("runtime", "unknown"),
        "audio_frontend_device": MODEL_INFO.get("audio_frontend_device", "unknown"),
        "video_frontend_device": MODEL_INFO.get("video_frontend_device", "unknown"),
        "device": "NVIDIA Jetson Orin Nano (MAXN Mode)",
        "total_test_samples": MODEL_INFO.get("total_test_samples", 0),
        "fold": MODEL_INFO.get("fold", ""),
        "accuracy_baseline": MODEL_INFO.get("accuracy_baseline", ""),
    }


@app.get("/api/live/step")
def get_live_step(step: Optional[int] = None):
    try:
        return stream_manager.step(target_step=step)
    except HTTPException:
        raise
    except Exception as e:
        logger.exception("Live step failed")
        raise HTTPException(status_code=500, detail=str(e))


@app.post("/api/live/reset")
def reset_live_simulation():
    return stream_manager.reset()


@app.get("/api/live/info")
async def get_live_simulation_info():
    return {
        "available": stream_manager.is_available(),
        "total_steps": stream_manager.total_steps,
        "window_sec": stream_manager.window_sec,
        "total_duration_sec": stream_manager.total_duration_sec,
        "session": "2022_6_19 · AM_100",
        "video_url": f"/samples/{stream_manager.video_rel}",
        "audio_url": f"/samples/{stream_manager.audio_rel}",
    }
